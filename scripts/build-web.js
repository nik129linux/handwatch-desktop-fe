#!/usr/bin/env node
/* Web build of Retoma for the cloud demo (Cloudflare static assets).
   The page is copied as is. js/web-bridge.js stands in for the Electron
   preload: it inlines the real ai/providers.js (same server calls, consent
   gates and rules fallback as the desktop app) and keeps events, quota and
   habit experiments in localStorage. Real window tracking stays desktop-only:
   a browser cannot see other windows, so the web build runs the demo data.
   Output: web-dist/ (gitignored). The app key ships in the page, as in the APK. */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'web-dist');
const API_BASE = (process.env.RETOMA_API_BASE || 'https://184-72-152-71.sslip.io').replace(/\/+$/, '');

function appKey() {
  if (process.env.RETOMA_APP_KEY) return process.env.RETOMA_APP_KEY;
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, 'ai', 'app-key.json'), 'utf8')).key || '';
  } catch (e) {
    return '';
  }
}

function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    const s = path.join(src, name);
    const d = path.join(dst, name);
    if (fs.statSync(s).isDirectory()) copyDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

const providersSrc = fs.readFileSync(path.join(ROOT, 'ai', 'providers.js'), 'utf8');

const BRIDGE = `/* Generated by scripts/build-web.js: browser stand-in for the Electron preload. */
(function () {
  'use strict';
  if (window.retoma) return;
  var process = { env: { RETOMA_API_BASE: ${JSON.stringify(API_BASE)}, RETOMA_APP_KEY: ${JSON.stringify(appKey())} } };
  function req(name) {
    if (name === './habits') return window.Habits;
    throw new Error('web build: no module ' + name);
  }
  var providers = (function (module, exports, require, process, __dirname) {
${providersSrc}
    return module.exports;
  })({ exports: {} }, {}, req, process, '');

  var habits = window.Habits;
  function modeOf(m) { return m === 'live' ? 'live' : 'demo'; }
  function readJson(key, fallback) {
    try { var raw = localStorage.getItem(key); return raw ? JSON.parse(raw) : fallback; } catch (e) { return fallback; }
  }
  function writeJson(key, value) {
    try { localStorage.setItem(key, JSON.stringify(value)); } catch (e) { /* private mode: memory only */ }
  }
  var EV = function (m) { return 'retoma.web.events.' + modeOf(m); };
  var EXP = function (m) { return 'retoma.web.experiments.' + modeOf(m); };
  var QUOTA = 'retoma.web.quota';
  function saveQuota(q) { if (q) writeJson(QUOTA, q); }
  function dayKey(ms) { var d = new Date(ms); return d.getFullYear() + '-' + (d.getMonth() + 1) + '-' + d.getDate(); }
  function metricsFor(m) { return habits.computeMetrics(readJson(EV(m), [])); }
  function withServer(opts) { return Object.assign({ apiBase: process.env.RETOMA_API_BASE, onQuota: saveQuota }, opts || {}); }
  function noop() {}

  window.retoma = {
    platform: 'web',
    propose: function (summary, opts) { return providers.propose(summary, withServer(opts)); },
    resumeLine: function (ctx, opts) { return providers.resumeLine(ctx, withServer(opts)); },
    previewPayload: function (summary, mode) { return Promise.resolve(providers.previewPayload(summary, mode)); },
    capabilities: function () { return Promise.resolve(providers.capabilities()); },
    loadEvents: function (m) { return Promise.resolve(readJson(EV(m), [])); },
    saveEvents: function (events, m) { writeJson(EV(m), events || []); return Promise.resolve(true); },
    deleteEvents: function (m) {
      try { localStorage.removeItem(EV(m)); localStorage.removeItem(EXP(m)); } catch (e) { /* ignore */ }
      return Promise.resolve(true);
    },
    notifyReturn: noop,
    setPaused: noop,
    onFocusResume: noop,
    onNoteFocus: noop,
    habitsReport: function (opts) {
      var o = opts || {};
      var m = modeOf(o.mode);
      var metrics = metricsFor(m);
      var exps = readJson(EXP(m), []);
      var evaluation = null;
      for (var i = exps.length - 1; i >= 0; i--) {
        var prev = exps[i];
        if (!prev || prev.status !== 'active') continue;
        var created = prev.createdAt ? dayKey(Date.parse(prev.createdAt)) : '';
        if (metrics && created && created !== dayKey(Date.now()) && habits.evaluateExperiment) {
          evaluation = habits.evaluateExperiment(prev, metrics);
          prev.status = 'done';
          prev.result = evaluation ? evaluation.status : 'unknown';
          writeJson(EXP(m), exps);
        }
        break;
      }
      return Promise.resolve(providers.habitsReport(metrics, { mode: o.aiMode || 'off', consent: o.consent || {}, onQuota: saveQuota }))
        .then(function (report) {
          return { metrics: metrics, report: report, evaluation: evaluation, quota: (report && report.quota) || null };
        });
    },
    habitsAccept: function (experiment, opts) {
      var m = modeOf((opts || {}).mode);
      if (!experiment || typeof experiment.text !== 'string' || !experiment.text) return Promise.resolve(false);
      var exps = readJson(EXP(m), []);
      exps.forEach(function (e) { if (e && e.status === 'active') e.status = 'done'; });
      exps.push(Object.assign({ id: 'exp-' + Date.now(), createdAt: new Date().toISOString(), status: 'active' }, experiment));
      writeJson(EXP(m), exps);
      return Promise.resolve(true);
    },
    habitsAsk: function (question, opts) {
      var o = opts || {};
      return Promise.resolve(providers.habitsAsk(metricsFor(o.mode), question, { mode: o.aiMode || 'off', consent: o.consent || {}, onQuota: saveQuota }));
    },
    aiStatus: function () { return Promise.resolve({ gated: true, reachable: false, model: '', url: '' }); },
    aiQuota: function () { return Promise.resolve(readJson(QUOTA, null)); },
    serverStatus: function () { return providers.serverStatus({ apiBase: process.env.RETOMA_API_BASE }); },
    setLang: noop
  };
})();
`;

fs.rmSync(OUT, { recursive: true, force: true });
for (const dir of ['css', 'js', 'fonts']) {
  if (fs.existsSync(path.join(ROOT, dir))) copyDir(path.join(ROOT, dir), path.join(OUT, dir));
}
fs.mkdirSync(path.join(OUT, 'ai'), { recursive: true });
fs.copyFileSync(path.join(ROOT, 'ai', 'habits.js'), path.join(OUT, 'ai', 'habits.js'));
fs.writeFileSync(path.join(OUT, 'js', 'web-bridge.js'), BRIDGE);

let html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const HABITS_TAG = '<script src="ai/habits.js"></script>';
if (!html.includes(HABITS_TAG)) throw new Error('index.html: ai/habits.js tag not found');
// The bridge needs window.Habits, and must exist before the app scripts read window.retoma.
html = html.replace(HABITS_TAG, HABITS_TAG + '\n<script src="js/web-bridge.js"></script>');
// Let the page reach the shared server; local Ollama is not reachable from the web.
html = html.replace(/connect-src ([^;"]*)/, function (_m, rest) { return 'connect-src ' + rest + ' ' + API_BASE; });
fs.writeFileSync(path.join(OUT, 'index.html'), html);

if (!appKey()) console.warn('warning: no app key, the server will answer 401');
console.log('web build: ' + OUT);
